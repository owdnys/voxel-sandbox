const edit = await page.evaluate(() => {
  const v = window.__voxel;
  v.player.pitch = -1.4;
  v.player.syncCamera();
  const hit = v.trace();
  if (!hit) return { error: 'no hit' };
  const before = v.world.get(...hit.block);
  v.interact(false);
  const broken = v.world.get(...hit.block);
  const next = v.trace();
  if (!next) return { before, broken, error: 'no placement target' };
  const cell = next.block.map((n, i) => n + next.normal[i]);
  const empty = v.world.get(...cell);
  v.interact(true);
  return { before, broken, cell, empty, placed: v.world.get(...cell), stored: JSON.parse(localStorage.getItem('block-wander-save-v1')).edits[cell.join(',')] };
});
await page.keyboard.press('KeyE');
