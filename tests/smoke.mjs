const boundary = await page.evaluate(() => {
  const w = window.__voxel.world;
  w.update(-16.5, 1.5, 2);
  w.buildNext(100);
  const adjacent = () => w.group.children.find(mesh => {
    if (mesh.material.transparent) return false;
    mesh.geometry.computeBoundingBox();
    const box = mesh.geometry.boundingBox;
    return box.min.x >= -16 && box.max.x <= 0 && box.min.z >= 0 && box.max.z <= 16;
  });
  const before = adjacent();
  const changed = w.set(-17, 30, 1, 3);
  return { before: !!before, changed, rebuilt: !!adjacent() && before !== adjacent() };
});
const collision = await page.evaluate(() => {
  const { world, player } = window.__voxel;
  player.position.set(3.5, 32.62, 3.5);
  world.set(4, 31, 3, 3);
  world.set(4, 32, 3, 3);
  player.moveAxis('x', 1);
  const wallX = player.position.x;
  player.position.set(3.5, 33.62, 3.5);
  world.set(3, 30, 3, 3);
  player.moveAxis('y', -3);
  const floorY = player.position.y;
  return { wallX, floorY };
});
